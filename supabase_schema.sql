-- =========================================================
-- Dual Soil Moisture Sensor Update
-- moisture_percent remains the overall average used for auto irrigation.
-- =========================================================

alter table public.sensor_readings add column if not exists moisture_1_raw integer;
alter table public.sensor_readings add column if not exists moisture_1_percent integer;
alter table public.sensor_readings add column if not exists moisture_2_raw integer;
alter table public.sensor_readings add column if not exists moisture_2_percent integer;

-- Force existing bad threshold values to be inside the allowed range.
update public.system_settings
set setting_value = jsonb_build_object(
  'light_lux', coalesce((setting_value->>'light_lux')::numeric, 150),
  'moisture_percent', least(100, greatest(0, coalesce((setting_value->>'moisture_percent')::numeric, 70))),
  'tray_water_percent', least(100, greatest(0, coalesce((setting_value->>'tray_water_percent')::numeric, 0)))
)
where setting_key = 'thresholds';

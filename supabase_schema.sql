-- Smart Green House System V12 database schema
-- Run this in Supabase SQL Editor.

create table if not exists public.sensor_readings (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone not null default now(),
  temperature double precision,
  humidity double precision,
  lux double precision,
  moisture_raw integer,
  moisture_percent integer,
  water_level_raw integer,
  water_level_percent integer,
  light_relay boolean default false,
  pump_relay boolean default false,
  tray_pump_relay boolean default false,
  fertilizer_relay boolean default false,
  light_on_seconds integer default 0,
  pump_on_seconds integer default 0,
  tray_pump_on_seconds integer default 0,
  fertilizer_on_seconds integer default 0
);

alter table public.sensor_readings add column if not exists water_level_raw integer;
alter table public.sensor_readings add column if not exists water_level_percent integer;
alter table public.sensor_readings add column if not exists tray_pump_relay boolean default false;
alter table public.sensor_readings add column if not exists fertilizer_relay boolean default false;
alter table public.sensor_readings add column if not exists light_on_seconds integer default 0;
alter table public.sensor_readings add column if not exists pump_on_seconds integer default 0;
alter table public.sensor_readings add column if not exists tray_pump_on_seconds integer default 0;
alter table public.sensor_readings add column if not exists fertilizer_on_seconds integer default 0;

create table if not exists public.device_controls (
  device_name text primary key,
  mode text not null default 'auto' check (mode in ('auto', 'manual')),
  target_state boolean not null default false,
  updated_at timestamp with time zone not null default now()
);

insert into public.device_controls (device_name, mode, target_state)
values
  ('light_bulb', 'auto', false),
  ('water_pump', 'auto', false),
  ('tray_pump', 'auto', false),
  ('fertilizer_pump', 'manual', false)
on conflict (device_name) do nothing;

create table if not exists public.device_events (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone not null default now(),
  device_name text not null,
  event_type text not null,
  duration_seconds integer default 0
);

create table if not exists public.system_alerts (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone not null default now(),
  alert_type text not null,
  message text not null,
  severity text default 'warning'
);

alter table public.sensor_readings enable row level security;
alter table public.device_controls enable row level security;
alter table public.device_events enable row level security;
alter table public.system_alerts enable row level security;

